// Quick View Metaobject Query
export const QUICK_VIEW_METAOBJECT_QUERY = `#graphql
  query QuickViewConfig($country: CountryCode, $language: LanguageCode) 
    @inContext(country: $country, language: $language) {
    metaobjects(type: "quick_view_config", first: 1) {
      nodes {
        fields {
          key
          value
          type
        }
      }
    }
  }
`;

// Product Item Fragment
export const PRODUCT_ITEM_FRAGMENT = `#graphql
  fragment MoneyProductItem on MoneyV2 {
    amount
    currencyCode
  }
  fragment ProductItem on Product {
    id
    handle
    title
    featuredImage {
      id
      altText
      url
      width
      height
    }
    priceRange {
      minVariantPrice {
        ...MoneyProductItem
      }
      maxVariantPrice {
        ...MoneyProductItem
      }
    }
    variants(first: 100) {
      nodes {
        id
        availableForSale
        selectedOptions {
          name
          value
        }
        price {
          amount
          currencyCode
        }
        compareAtPrice {
          amount
          currencyCode
        }
      }
    }
    options {
      name
      values
    }
    images(first: 10) {
      nodes {
        url
        altText
      }
    }
  }
`;

// Product Variant Fragment with Metaobject Support
